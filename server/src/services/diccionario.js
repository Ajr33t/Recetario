/** Inverso ES → EN (solo la primera coincidencia gana). */
export const INVERSO = Object.fromEntries(Object.entries(DICCIONARIO).map(([en, es]) => [es, en]));

/**
 * Aplica el diccionario a un texto (coincidencia exacta, sin distinguir mayúsculas)
 * conservando la capitalización del original.
 * @returns {string|null} traducción o null si no está en el diccionario
 */
export function conDiccionario(texto) {
  if (!texto) return null;
  const min = texto.trim().toLowerCase();
  const valor = DICCIONARIO[min];
  if (!valor) return null;
  // Respeta Title Case / MAYÚSCULAS del original
  if (texto.trim() === texto.trim().toUpperCase() && /[A-ZÁÉÍÓÚ]/.test(texto)) {
    return valor.toUpperCase();
  }
  if (texto.trim()[0] === texto.trim()[0].toUpperCase()) {
    return valor.charAt(0).toUpperCase() + valor.slice(1);
  }
  return valor;
}

/**
 * Traduce una consulta del usuario en español a inglés (para TheMealDB).
 * Si no hay coincidencia exacta se devuelve el texto tal cual.
 */
export function aIngles(texto) {
  if (!texto) return texto;
  const min = texto.trim().toLowerCase();
  const en = INVERSO[min];
  return en || texto;
}
